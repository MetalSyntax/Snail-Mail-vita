typedef enum {
    MI_SHOOT = 0,
    MI_LEFT,
    MI_RIGHT,
    MI_PAUSE,
    MI_DEADZONE,
    MI_SENS,
    MI_RESET,
    MI_CLOSE,
    MI_COUNT
} MenuItem;

static int s_open = 0;
static int s_selected = 0;
static int s_capturing = -1; // indice de item en captura, -1 = no
static int s_cooldown = 0;

void controls_menu_init(void) {
    s_open = 0;
    s_selected = 0;
    s_capturing = -1;
    s_cooldown = 0;
}

int controls_menu_is_open(void) {
    return s_open;
}

// Pool immediate-mode de vitaGL (ffp.c). vitaGL lo reserva del pool circular
// en CADA inicio de escena, asi que solo lo pedimos con el menu abierto.
// Debe fijarse antes del primer draw del frame (open/close corren antes de
// nativeRender). Peor caso del overlay ~2.4k quads * 4 * 88 B ~= 860 KB.
extern int legacy_pool_size;
#define MENU_LEGACY_POOL_SIZE (2 * 1024 * 1024)

void controls_menu_open(void) {
    legacy_pool_size = MENU_LEGACY_POOL_SIZE;
    s_open = 1;
    s_selected = 0;
    s_capturing = -1;
    s_cooldown = 12; // evita que el CROSS de apertura dispare acciones
    l_info("controls_menu: opened (START+SELECT)");
}

void controls_menu_close(void) {
    if (!s_open) return;
    s_open = 0;
    legacy_pool_size = 0;
    s_capturing = -1;
    controls_save();
    s_cooldown = 12;
    l_info("controls_menu: closed, config saved");
}

static uint32_t *item_button_ptr(int item) {
    switch (item) {
        case MI_SHOOT: return &g_controls.btn_shoot;
        case MI_LEFT:  return &g_controls.btn_steer_left;
        case MI_RIGHT: return &g_controls.btn_steer_right;
        case MI_PAUSE: return &g_controls.btn_pause;
        default: return NULL;
    }
}

int controls_menu_update(uint32_t buttons, uint32_t just_pressed) {
    (void)buttons;
    if (!s_open) return 0;
    if (s_cooldown > 0) {
        s_cooldown--;
        return 1; // sigue consumiendo input durante el cooldown
    }

    // ---- modo captura: esperar un boton ----
    if (s_capturing >= 0) {
        if (just_pressed & SCE_CTRL_SELECT) {
            s_capturing = -1; // SELECT cancela sin asignar
            return 1;
        }
        uint32_t btn = controls_button_from_mask(just_pressed);
        if (btn) {
            uint32_t *dst = item_button_ptr(s_capturing);
            if (dst) {
                *dst = btn;
                char name[64];
                controls_mask_to_string(btn, name, sizeof(name));
                l_info("controls_menu: item %d -> %s", s_capturing, name);
                controls_save();
            }
            s_capturing = -1;
        }
        return 1;
    }

    if (just_pressed & SCE_CTRL_UP) {
        s_selected = (s_selected + MI_COUNT - 1) % MI_COUNT;
    } else if (just_pressed & SCE_CTRL_DOWN) {
        s_selected = (s_selected + 1) % MI_COUNT;
    }

    // Ajustes con LEFT/RIGHT en filas numericas
    if (s_selected == MI_DEADZONE) {
        if (just_pressed & SCE_CTRL_LEFT) {
            g_controls.deadzone -= 5;
            if (g_controls.deadzone < 5) g_controls.deadzone = 5;
            controls_save();
        } else if (just_pressed & SCE_CTRL_RIGHT) {
            g_controls.deadzone += 5;
            if (g_controls.deadzone > 50) g_controls.deadzone = 50;
            controls_save();
        }
    } else if (s_selected == MI_SENS) {
        if (just_pressed & SCE_CTRL_LEFT) {
            g_controls.sensitivity -= 10;
            if (g_controls.sensitivity < 20) g_controls.sensitivity = 20;
            controls_save();
        } else if (just_pressed & SCE_CTRL_RIGHT) {
            g_controls.sensitivity += 10;
            if (g_controls.sensitivity > 300) g_controls.sensitivity = 300;
            controls_save();
        }
    }

    if (just_pressed & SCE_CTRL_CROSS) {
        if (s_selected >= MI_SHOOT && s_selected <= MI_PAUSE) {
            s_capturing = s_selected; // entrar en captura
        } else if (s_selected == MI_RESET) {
            controls_reset_defaults();
        } else if (s_selected == MI_CLOSE) {
            controls_menu_close();
        }
        return 1;
    }

    if (just_pressed & SCE_CTRL_CIRCLE) {
        controls_menu_close();
        return 1;
    }

    return 1; // menu abierto consume todo el input del juego
}

/* ---------- dibujo (un solo batch immediate-mode) ---------- */

// Emite un quad con el color actual. Debe llamarse dentro de glBegin(GL_QUADS).
static void emit_quad(float x0, float y0, float x1, float y1) {
    glVertex2f(x0, y0);
    glVertex2f(x1, y0);
    glVertex2f(x1, y1);
    glVertex2f(x0, y1);
}

static void emit_text(const char *s, float x, float y, int scale) {
    float cx = x;
    while (*s) {
        unsigned char c = (unsigned char)*s++;
        if (c == '\n') {
            cx = x;
            y += 8 * scale + 2;
            continue;
        }
        if (c >= 128) c = '?';
        const unsigned char *glyph = s_font[c];
        for (int row = 0; row < 8; row++) {
            unsigned char bits = glyph[row];
            // font8x8_basic: el bit menos significativo es el pixel
            // izquierdo (col 0 = 1<<0). Usar (7-col) espeja cada
            // glifo horizontalmente (bug visto en hardware: texto
            // espejado con el orden conservado).
            // Un quad por tramo horizontal de pixeles (~2.5x menos vertices
            // que uno por pixel): cada vertice immediate-mode ocupa 88 B.
            for (int col = 0; col < 8; col++) {
                if (!(bits & (1 << col))) continue;
                int end = col;
                while (end + 1 < 8 && (bits & (1 << (end + 1)))) end++;
                float py = y + row * scale;
                emit_quad(cx + col * scale, py, cx + (end + 1) * scale, py + scale);
                col = end;
            }
        }
        cx += 8 * scale + scale; // 1px de tracking
    }
}

static int text_w(const char *s, int scale) {
    return (int)strlen(s) * 9 * scale - scale;
}

void controls_menu_draw(void) {
    if (!s_open) return;

    /* Aislamiento estricto de estado (Fase 11: evita tinte verde por
     * GLColour cacheado del motor). */
    float prev_color[4] = { 1, 1, 1, 1 };
    glGetFloatv(GL_CURRENT_COLOR, prev_color);
    glPushAttrib(GL_ALL_ATTRIB_BITS);

    glMatrixMode(GL_PROJECTION);
    glPushMatrix();
    glLoadIdentity();
    glOrthof(0.0f, 960.0f, 544.0f, 0.0f, -1.0f, 1.0f);
    glMatrixMode(GL_MODELVIEW);
    glPushMatrix();
    glLoadIdentity();

    glDisable(GL_TEXTURE_2D);
    glDisable(GL_DEPTH_TEST);
    glDisable(GL_FOG);
    glDisable(GL_LIGHTING);
    glDisable(GL_CULL_FACE);
    glEnable(GL_BLEND);
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);

    // Todo el overlay en un unico glBegin/glEnd: 1 sola draw call y uso
    // acotado del legacy pool (~30k verts peor caso << 2 MB).
    glBegin(GL_QUADS);

    // Fondo atenuado
    glColor4f(0.0f, 0.0f, 0.0f, 0.65f);
    emit_quad(0, 0, 960, 544);

    // Caja central
    const float bx0 = 180, by0 = 52, bx1 = 780, by1 = 492;
    glColor4f(0.03f, 0.05f, 0.10f, 0.96f);
    emit_quad(bx0, by0, bx1, by1);
    // Borde superior (acento)
    glColor4f(0.0f, 0.65f, 1.0f, 1.0f);
    emit_quad(bx0, by0, bx1, by0 + 4);
    // Marco fino
    glColor4f(0.0f, 0.65f, 1.0f, 0.8f);
    emit_quad(bx0, by0, bx0 + 2, by1);
    emit_quad(bx1 - 2, by0, bx1, by1);
    emit_quad(bx0, by1 - 2, bx1, by1);

    const int S = 2; // escala de fuente
    const char *title = "CONTROLS";
    glColor4f(1.0f, 0.85f, 0.2f, 1.0f);
    emit_text(title, 480 - text_w(title, S) / 2, by0 + 18, S);
    const char *sub = "START+SELECT OPEN/CLOSE - CROSS CHANGE";
    glColor4f(0.55f, 0.75f, 0.95f, 1.0f);
    emit_text(sub, 480 - text_w(sub, 1) / 2, by0 + 40, 1);

    char val[64], line[96];
    float ry = by0 + 72;
    const float row_h = 34;
    const float vx = 560; // columna de valores

    for (int i = 0; i < MI_COUNT; i++) {
        int sel = (i == s_selected);
        if (sel) {
            glColor4f(0.0f, 0.35f, 0.65f, 0.9f);
            emit_quad(bx0 + 16, ry - 4, bx1 - 16, ry + 24);
        }
        float tr = sel ? 1.0f : 0.75f;
        float tg = sel ? 1.0f : 0.80f;
        float tb = sel ? 1.0f : 0.85f;

        switch (i) {
            case MI_SHOOT:
                controls_mask_to_string(g_controls.btn_shoot, val, sizeof(val));
                snprintf(line, sizeof(line), "SHOOT");
                break;
            case MI_LEFT:
                controls_mask_to_string(g_controls.btn_steer_left, val, sizeof(val));
                snprintf(line, sizeof(line), "STEER LEFT");
                break;
            case MI_RIGHT:
                controls_mask_to_string(g_controls.btn_steer_right, val, sizeof(val));
                snprintf(line, sizeof(line), "STEER RIGHT");
                break;
            case MI_PAUSE:
                controls_mask_to_string(g_controls.btn_pause, val, sizeof(val));
                snprintf(line, sizeof(line), "PAUSE");
                break;
            case MI_DEADZONE:
                snprintf(val, sizeof(val), "< %d%% >", g_controls.deadzone);
                snprintf(line, sizeof(line), "DEADZONE");
                break;
            case MI_SENS:
                snprintf(val, sizeof(val), "< %d%% >", g_controls.sensitivity);
                snprintf(line, sizeof(line), "SENSITIVITY");
                break;
            case MI_RESET:
                snprintf(val, sizeof(val), "[OK]");
                snprintf(line, sizeof(line), "RESET DEFAULTS");
                break;
            case MI_CLOSE:
                snprintf(val, sizeof(val), "[OK]");
                snprintf(line, sizeof(line), "CLOSE");
                break;
            default:
                line[0] = 0; val[0] = 0;
                break;
        }

        glColor4f(tr, tg, tb, 1.0f);
        emit_text(line, bx0 + 36, ry, S);
        if (i <= MI_PAUSE || i == MI_DEADZONE || i == MI_SENS) {
            if (s_capturing == i) {
                glColor4f(1.0f, 0.3f, 0.3f, 1.0f);
                emit_text("PRESS BUTTON...", vx, ry, S);
            } else {
                float vr = sel ? 0.4f : 0.6f, vg = sel ? 1.0f : 0.85f;
                glColor4f(vr, vg, 1.0f, 1.0f);
                emit_text(val, vx, ry, S);
            }
        } else {
            glColor4f(0.5f, 0.7f, 0.9f, 1.0f);
            emit_text(val, vx, ry, 1);
        }
        ry += row_h;
    }

    if (s_capturing >= 0) {
        const char *msg = "PRESS A BUTTON - SELECT CANCELS";
        glColor4f(1.0f, 0.4f, 0.4f, 1.0f);
        emit_text(msg, 480 - text_w(msg, 1) / 2, by1 - 52, 1);
    } else {
        const char *hint = "UP/DOWN SELECT - CROSS EDIT - CIRCLE CLOSE";
        glColor4f(0.55f, 0.75f, 0.95f, 1.0f);
        emit_text(hint, 480 - text_w(hint, 1) / 2, by1 - 52, 1);
        const char *hint2 = "SAVED TO controls.txt AUTOMATICALLY";
        glColor4f(0.45f, 0.55f, 0.65f, 1.0f);
        emit_text(hint2, 480 - text_w(hint2, 1) / 2, by1 - 32, 1);
    }

    glEnd();

    // Restaurar estado y forzar blanco (anti-tinte Fase 11)
    glMatrixMode(GL_MODELVIEW);
    glPopMatrix();
    glMatrixMode(GL_PROJECTION);
    glPopMatrix();
    glMatrixMode(GL_MODELVIEW);
    glPopAttrib();
    glColor4f(1.0f, 1.0f, 1.0f, 1.0f);
    (void)prev_color;
}
